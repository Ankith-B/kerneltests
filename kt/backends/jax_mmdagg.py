"""JAX backend for MMDAgg: jit-compiled kernel matrices and bootstrap/permutation statistics.

The random draws (Rademacher matrix R or permutation matrices V) are generated by the
NumPy ``RandomState`` protocol in :func:`kt.mmdagg.mmdagg` and passed in, so both
backends see identical resamples. Distances, kernel matrices (all bandwidths of one
kernel batched with ``jax.vmap``) and the quadratic forms r^T K r are computed in JAX
in float64. Runs on whatever device JAX selects (CPU, or GPU with a CUDA jaxlib).
"""
from __future__ import annotations
from functools import partial

import numpy as np

from . import require_jax

jax = require_jax()
import jax.numpy as jnp  # noqa: E402

_MEM_BUDGET = 1 << 30  # bytes of kernel matrices materialised per vmap batch


def _kernel(d, base):
    if base == "gaussian":
        return jnp.exp(-d ** 2)
    if base == "imq":
        return (1 + d ** 2) ** (-0.5)
    if base == "matern_0.5":
        return jnp.exp(-d)
    if base == "matern_1.5":
        return (1 + np.sqrt(3) * d) * jnp.exp(-np.sqrt(3) * d)
    if base == "matern_2.5":
        return (1 + np.sqrt(5) * d + 5 / 3 * d ** 2) * jnp.exp(-np.sqrt(5) * d)
    if base == "matern_3.5":
        return (1 + np.sqrt(7) * d + 2 * 7 / 5 * d ** 2 + 7 * np.sqrt(7) / 3 / 5 * d ** 3) * jnp.exp(-np.sqrt(7) * d)
    if base == "matern_4.5":
        return (1 + 3 * d + 3 * (6 ** 2) / 28 * d ** 2 + (6 ** 3) / 84 * d ** 3
                + (6 ** 4) / 1680 * d ** 4) * jnp.exp(-3 * d)
    raise ValueError(f"unknown kernel {base!r}")


def _base(kernel):
    if kernel in ("gaussian", "imq"):
        return kernel
    return "matern_0.5" if kernel == "laplace" else kernel[:10]


@partial(jax.jit, static_argnames="metric")
def _pairwise(A, B, metric):
    diff = A[:, None, :] - B[None, :, :]
    if metric == "cityblock":
        return jnp.sum(jnp.abs(diff), -1)
    return jnp.sqrt(jnp.sum(diff ** 2, -1))


@partial(jax.jit, static_argnames="base")
def _wild(Pxx, Pyy, Pxy, bws, Rn, base):
    n = Pxx.shape[0]
    off = 1.0 - jnp.eye(n)

    def one(bw):
        H = (_kernel(Pxx / bw, base) + _kernel(Pyy / bw, base)
             - _kernel(Pxy / bw, base) - _kernel(Pxy.T / bw, base)) * off
        return jnp.sum(Rn * (H @ Rn), 0)
    return jax.vmap(one)(bws)


@partial(jax.jit, static_argnames=("base", "m", "n"))
def _perm(P, bws, V10, V01, V11, base, m, n):
    off = 1.0 - jnp.eye(P.shape[0])

    def one(bw):
        K = _kernel(P / bw, base) * off
        return (jnp.sum(V10 * (K @ V10), 0) * (n - m + 1) / (m * n * (m - 1))
                + jnp.sum(V01 * (K @ V01), 0) * (m - n + 1) / (m * n * (n - 1))
                + jnp.sum(V11 * (K @ V11), 0) / (m * n))
    return jax.vmap(one)(bws)


def statistics(X, Y, kbl, wild, draws):
    """Return the (#kernels*#bandwidths, B1+B2+1) matrix of bootstrap/permutation statistics.

    kbl: list of (kernel name, bandwidths, metric); draws: (Rn,) if wild else (V10, V01, V11).
    """
    m, n = X.shape[0], Y.shape[0]
    Xj, Yj = jnp.asarray(X), jnp.asarray(Y)
    side = n if wild else m + n
    per_bw = (4 if wild else 1) * side * side * 8
    batch = max(1, _MEM_BUDGET // per_bw)
    dev = [jnp.asarray(a) for a in draws]
    cache, rows = {}, []
    for kern, bandwidths, metric in kbl:
        if metric not in cache:
            if wild:
                cache = {metric: (_pairwise(Xj, Xj, metric), _pairwise(Yj, Yj, metric),
                                  _pairwise(Xj, Yj, metric))}
            else:
                Z = jnp.vstack((Xj, Yj))
                cache = {metric: (_pairwise(Z, Z, metric),)}
        P = cache[metric]
        bws = jnp.asarray(bandwidths, dtype=jnp.float64)
        for s in range(0, len(bandwidths), batch):
            b = bws[s:s + batch]
            if wild:
                rows.append(_wild(*P, b, dev[0], base=_base(kern)))
            else:
                rows.append(_perm(P[0], b, *dev, base=_base(kern), m=m, n=n))
    return np.asarray(jnp.concatenate(rows, 0))
